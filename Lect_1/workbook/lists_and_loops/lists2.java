/* A static list.  */
public class lists2 {
    
    // Create a new list
    static Integer[] integerArray = new Integer[5];


    public static void main (String[] args) {
        integerArray[0] = 10;                // insert 10 into the list
        System.out.println(integerArray[0]);  // call integer value 10 with an index of 0.
    }
}
